class PFSA(nn.Module):
    """
    Parameter-free Fusion and Spatial Attention (PFSA)
    2026年最新论文提出的无参数轻量化融合模块，用于替换深层门控(MCFG)，防止特征退化。
    """
    def __init__(self, ch):
        super().__init__()
        # 无需定义任何可学习参数（如 Linear 或 Conv），极致轻量！

    def forward(self, x):
        # x 接收来自双流的特征列表: [x_rgb, x_ir]
        x_rgb, x_ir = x[0], x[1]

        # 1. 沿通道维度拼接 [B, 2C, H, W]
        f_concat = torch.cat([x_rgb, x_ir], dim=1)

        # 2. 通道级平均池化 (CAP) -> [B, 1, H, W]
        cap = torch.mean(f_concat, dim=1, keepdim=True)

        # 3. 通道级最大池化 (CMP) -> [B, 1, H, W]
        cmp, _ = torch.max(f_concat, dim=1, keepdim=True)

        # 4. 空间注意力加权 (逐元素相乘) -> [B, 2C, H, W]
        f_w = f_concat * torch.sigmoid(cap * cmp)

        # 5. 分离回 RGB 和 IR 的加权特征
        c = x_rgb.shape[1]
        f_rgb_w, f_ir_w = torch.split(f_w, c, dim=1)

        # 6. 最终融合 (带有残差连接的相加，保护原有的预训练特征不丢失)
        f_fused = x_rgb + f_rgb_w + x_ir + f_ir_w
        return f_fused


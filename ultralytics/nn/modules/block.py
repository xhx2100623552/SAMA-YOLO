class ECA(nn.Module):
    """Efficient Channel Attention module."""
    def __init__(self, c1, c2=None, b=1, gamma=2):
        super(ECA, self).__init__()
        # c1 是输入通道数，这里 c2 只是为了兼容 YOLO 的解析器占位
        t = int(abs((math.log(c1, 2) + b) / gamma))
        k = t if t % 2 else t + 1  # 确保卷积核大小是奇数
        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.conv = nn.Conv1d(1, 1, kernel_size=k, padding=(k - 1) // 2, bias=False)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        # x shape: [batch, channels, height, width]
        y = self.avg_pool(x) # 全局平均池化
        y = self.conv(y.squeeze(-1).transpose(-1, -2)).transpose(-1, -2).unsqueeze(-1)
        return x * self.sigmoid(y) # 将权重乘回原特征图
class MEAF(nn.Module):
    def __init__(self, c1, c2, c=1.0, k=3):
        super().__init__()
        self.c_half = c1 // 2 
        
        # 1. 通道增强 (确保 ECA 导入正常)
        self.attn_v = ECA(self.c_half)
        self.attn_i = ECA(self.c_half)

        # 2. 空间注意力生成器
        self.conv_v = nn.Conv2d(self.c_half, 1, 1)
        self.conv_i = nn.Conv2d(self.c_half, 1, 1)
        
        self.mask_generator = nn.Sequential(
            nn.Conv2d(2, 1, kernel_size=7, padding=3, bias=False),
            nn.Sigmoid()
        )

        # 3. 最终融合投影
        self.final_conv = Conv(c1, c2, 1, 1)

    def forward(self, x):
        # 解包 RGB 和 IR
        x_v, x_i = x 
        
        # 1. 模态增强
        xv_enhanced = self.attn_v(x_v)
        xi_enhanced = self.attn_i(x_i)
        
        # 2. 生成初步 Mask
        mask_v = self.conv_v(xv_enhanced)
        mask_i = self.conv_i(xi_enhanced)
        
        # 🎯 【关键修复】：如果 mask_i 大小不对，强制缩放到 mask_v 的大小
        if mask_v.shape[2:] != mask_i.shape[2:]:
            mask_i = F.interpolate(mask_i, size=mask_v.shape[2:], mode='nearest')
            xi_enhanced = F.interpolate(xi_enhanced, size=xv_enhanced.shape[2:], mode='nearest')
        
        # 3. 混合掩码生成
        mask = self.mask_generator(torch.cat([mask_v, mask_i], dim=1))
        
        # 4. 掩码应用
        xv_masked = xv_enhanced * (mask + 0.5)
        xi_masked = xi_enhanced * (2.0 - mask)
        
        # 5. 拼接输出
        return self.final_conv(torch.cat([xv_masked, xi_masked], dim=1))


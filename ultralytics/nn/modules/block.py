class HighFrequencyPerception(nn.Module):
    """
    High Frequency Perception (HFP) Module.
    利用快速傅里叶变换 (FFT) 增强高频边缘特征，抑制低频背景噪声。
    专为极小目标 (Tiny Object) 检测设计。
    """
    # 这里的参数对应你 YAML 里的 [[0.25, 0.25], [8, 8], 32]
    def __init__(self, c1, c2, ratios=[0.25, 0.25], window_size=[8, 8], dim=32):
        super().__init__()
        # 1. 确保通道数对齐 (如果输入输出不一致，用 1x1 卷积调整)
        self.align = nn.Conv2d(c1, c2, kernel_size=1, stride=1, padding=0, bias=False) if c1 != c2 else nn.Identity()
        
        # 2. 可学习的频域响应权重 (让网络自己学哪些频率重要)
        self.freq_weight = nn.Parameter(torch.ones(1, c2, 1, 1))
        
        # 3. 空间域特征融合卷积
        self.fuse = nn.Sequential(
            nn.Conv2d(c2 * 2, c2, kernel_size=1, stride=1, padding=0, bias=False),
            nn.BatchNorm2d(c2),
            nn.SiLU(inplace=True)
        )

    def forward(self, x):
        # 通道对齐
        x_aligned = self.align(x)
        
        # ---------------- 核心：频域高频感知 ----------------
        
        # 1. FFT 正变换：将空间域转换到频域 (使用 rfft2 速度更快，省显存)
        # norm='ortho' 保证正逆变换的能量守恒
        freq = torch.fft.rfft2(x_aligned, norm='ortho')
        
        # 2. 频域调制：用可学习权重放大高频边缘信号
        freq_modulated = freq * self.freq_weight
        
        # 3. iFFT 逆变换：将干净的高频特征还原回空间域
        # 必须指定输出尺寸 s，防止特征图长宽为奇数时尺寸发生形变
        spatial_high_freq = torch.fft.irfft2(
            freq_modulated, 
            s=(x_aligned.shape[2], x_aligned.shape[3]), 
            norm='ortho'
        )
        
        # ---------------------------------------------------
        
        # 4. 残差融合：将原图特征与提取出的高频轮廓拼接，并融合回原维度
        out = self.fuse(torch.cat([x_aligned, spatial_high_freq], dim=1))
        
        return out
class IAFusion(nn.Module):
    """
    Illumination-Aware Feature Fusion Module (Inspired by UA-CMDet).
    动态评估当前场景的“光照/有效性”，为 RGB 和 IR 分配自适应权重。
    """
    def __init__(self, c1, c2):
        """
        初始化 IAFusion。由于是 YOLO 里的 Concat 替代品，这里 c1 通常是列表。
        c1: [ch_rgb, ch_ir] 输入通道数列表
        c2: 输出通道数（通常等于 ch_rgb + ch_ir，如果后面接 C3k2 压缩的话）
        """
        super().__init__()
        # 提取各个模态的通道数
        self.ch_rgb = c1[0]
        self.ch_ir = c1[1]
        
        # 光照感知网络 (Illumination Assessment Network)
        # 用来生成两个模态的权重
        self.gap = nn.AdaptiveAvgPool2d(1)
        self.fc = nn.Sequential(
            nn.Linear(self.ch_rgb + self.ch_ir, (self.ch_rgb + self.ch_ir) // 4, bias=False),
            nn.ReLU(inplace=True),
            nn.Linear((self.ch_rgb + self.ch_ir) // 4, 2, bias=False), # 输出 2 个权重: W_rgb, W_ir
            nn.Sigmoid() # 将权重限制在 0~1 之间
        )

    def forward(self, x):
        """
        x: 一个列表 [x_rgb, x_ir]，分别来自两个骨干网络
        """
        x_rgb, x_ir = x[0], x[1]
        
        # 1. 拼接特征以提取全局光照上下文
        x_cat = torch.cat([x_rgb, x_ir], dim=1) # [B, C1+C2, H, W]
        
        # 2. 全局平均池化得到特征向量
        b, c, _, _ = x_cat.size()
        y = self.gap(x_cat).view(b, c) # [B, C1+C2]
        
        # 3. 通过全连接层计算权重
        weights = self.fc(y) # [B, 2]
        w_rgb = weights[:, 0].view(b, 1, 1, 1)
        w_ir = weights[:, 1].view(b, 1, 1, 1)
        
        # 4. 权重加持：根据光照条件强化或抑制对应模态
        out_rgb = x_rgb * w_rgb
        out_ir = x_ir * w_ir
        
        # 5. 返回拼接后的加权特征，供下一层的 C3k2 进一步融合
        return torch.cat([out_rgb, out_ir], dim=1)
